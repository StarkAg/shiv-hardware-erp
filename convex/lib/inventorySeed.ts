/** Match only the supplied brand / thickness / size, including old bill names. */
export function seedRefForName(name: string): string | undefined {
  const normalized = name.toLowerCase().replace(/[.]/g, " ").replace(/×/g, "x").replace(/\s+/g, " ").trim();
  const match = normalized.match(/^(\d+)\s*mm\s+(.+?)\s+(\d+)\s*x\s*(\d+(?:\s+\d+)?)\s*(?:ft)?$/);
  if (!match) return undefined;
  const [, thickness, description, height, width] = match;
  const brand = /^(?:sg|solid sg|signature gold)$/.test(description) ? "Signature Gold"
    : /^(?:s|s ply|b board s|solid s|signature)$/.test(description) ? "Signature"
    : /^(?:milton|milton super(?: pro| gold)?|milton hs)$/.test(description) ? "Milton" : undefined;
  const size = `${height}x${width.replace(" ", ".")}`;
  return INVENTORY_SEED.find(i => i.brand === brand && i.mm === Number(thickness) && i.size === size)?.ref;
}
