/** One pose from the sprite sheet, drawn large and square. */
import sheet from './art/sprites.png'
import meta from './art/sprites.json'

export function Sprite({ frame, scale = 2, flip = false, className = '' }) {
  const size = meta.cell * scale
  const i = meta.frames[frame] ?? 0
  return (
    <span
      className={`ck-sprite ${className}`}
      aria-hidden="true"
      style={{
        width: size,
        height: size,
        backgroundImage: `url(${sheet})`,
        backgroundSize: `${size * meta.count}px ${size}px`,
        backgroundPosition: `${-i * size}px 0`,
        transform: flip ? 'scaleX(-1)' : undefined,
      }}
    />
  )
}

