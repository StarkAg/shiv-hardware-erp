export function PixelIcon({ id, size = 24 }) {
  const rects = []
  ;(ICONS[id] || []).forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const c = row[x]
      if (c === '#') rects.push(<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="currentColor" />)
      else if (c === '+') rects.push(<rect key={`${x}-${y}`} x={x} y={y} width="1" height="1" fill="currentColor" opacity=".55" />)
    }
  })
  return <svg viewBox="0 0 16 16" width={size} height={size} shapeRendering="crispEdges" aria-hidden="true">{rects}</svg>
}
